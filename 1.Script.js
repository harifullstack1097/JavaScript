// Addition of two numbers in JS
var num1 = 15;
var num2 = 35;
var sum = num1 + num2;
console.log("The sum of num1 and num2 is: " + sum);


// Subtraction of two numbers in JS
var diff = num2 - num1;
console.log("The difference of num2 and num1 is: " + diff);   


// Multiplication of two numbers in JS
var prod = num1 * num2;
console.log("The product of num1 and num2 is: " + prod);   


// Division of two numbers in JS
var div = num2 / num1;
console.log("The division of num2 by num1 is: " + div);


// Modulus of two numbers in JS
var mod = num2 % num1;
console.log("The modulus of num2 by num1 is: " + mod);    


// Increment of a number in JS
num1++;
console.log("The incremented value of num1 is: " + num1); 


// Decrement of a number in JS
num2--;
console.log("The decremented value of num2 is: " + num2); 
